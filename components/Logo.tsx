/**
 * @param draw  "mount" draws on mount, "view" draws when scrolled into view.
 */
export function LogoMark({
  className = "",
  draw,
  title,
}: {
  className?: string;
  draw?: "mount" | "view";
  title?: string;
}) {
  const reduce = useReducedMotion();
  const animated = draw && !reduce;
  const target = { pathLength: 1, fillOpacity: 1 };
  return (
    <svg
      viewBox="-1 -1 198.31 92.54"
      className={className}
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : true}
      aria-label={title}
    >
      {PATHS.map((d, i) =>
        animated ? (
          <m.path
            key={i}
            d={d}
            fill="currentColor"
            stroke="currentColor"
            strokeWidth={0.9}
            initial={{ pathLength: 0, fillOpacity: 0 }}
            {...(draw === "mount"
              ? { animate: target }
              : { whileInView: target, viewport: { once: true, margin: VIEW_MARGIN } })}
            transition={{
              pathLength: { duration: 1.6, delay: i * 0.18, ease: EASE },
              fillOpacity: { duration: 0.8, delay: 1.1 + i * 0.18 },
            }}
          />
        ) : (
          <path key={i} d={d} fill="currentColor" />
        ),
      )}
    </svg>
  );
}
